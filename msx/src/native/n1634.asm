; Native $1634-$16D0: dispatch the eight scenery/object slots (Y=2..9).
; Each vector is indexed by twice its type, stored at $0060/$0061, then
; entered through the original far-call trampoline so a target can change
; the mapped code segment.  Final slot tail-jumps as in the 6502 routine.
; Keep X in E, Y in C, A and carry from the vector high byte.

	ld c,2
	ld a,($16D6)
	sla a
	ld e,a
	ld hl,$1737
	ex af,af'
	add hl,de
	ex af,af'
	ld a,(hl)
	ld ($0060),a
	inc hl
	ld a,(hl)
	inc a
	dec a
	ld ($0061),a
	ld hl,($0060)
